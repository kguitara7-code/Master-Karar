export function parseRepoFileToProgram(file: RepoFile, repoPath = DEFAULT_REPO_PATH): ProgramInfo {
  const meta = ENRICHED_METADATA[file.path] || {};
  const filename = file.path;
  
  // determine extension
  let ext: ProgramInfo['extension'] = 'other';
  if (filename.toLowerCase().endsWith('.exe')) ext = 'exe';
  else if (filename.toLowerCase().endsWith('.zip')) ext = 'zip';
  else if (filename.toLowerCase().endsWith('.rar')) ext = 'rar';
  else if (filename.toLowerCase().endsWith('.md')) ext = 'md';

  // determine category heuristic if not enriched
  let cat: ProgramInfo['category'] = meta.category || 'drivers_utilities';
  if (!meta.category) {
    if (filename.toLowerCase().includes('3u')) cat = 'apple_flashing';
    else if (filename.toLowerCase().includes('desk') || filename.toLowerCase().includes('viewer')) cat = 'remote_access';
    else if (filename.toLowerCase().includes('borneo') || filename.toLowerCase().includes('jcid')) cat = 'schematics_hardware';
  }

  return {
    id: file.oid || filename,
    filename,
    name: meta.name || filename,
    arabicName: meta.arabicName || filename,
    version: meta.version || '1.0',
    category: cat,
    categoryLabelAr: meta.categoryLabelAr || 'أدوات الصيانة والبرامج',
    categoryLabelEn: meta.categoryLabelEn || 'Maintenance & Utilities',
    taglineAr: meta.taglineAr || 'ملف برمجي متاح للتنزيل المباشر',
    taglineEn: meta.taglineEn || 'Direct download software binary',
    logoUrl: meta.logoUrl,
    previewImageUrl: meta.previewImageUrl,
    descriptionAr: meta.descriptionAr || `ملف برنامج ${filename} جاهز للتنزيل المباشر من المستودع`,
    descriptionEn: meta.descriptionEn || `Software file ${filename} ready for direct download from repository`,
    featuresAr: meta.featuresAr || ['تنزيل مباشر عالي السرعة من سيرفرات Hugging Face', 'ملف أصلي ومحمي برمز تجزئة آمن'],
    featuresEn: meta.featuresEn || ['Direct high-speed download from Hugging Face LFS', 'Verified checksum integrity'],
    iconType: meta.iconType || (ext === 'zip' || ext === 'rar' ? 'archive' : 'driver'),
    brandColor: meta.brandColor || '#3B82F6',
    secondaryColor: meta.secondaryColor || '#60A5FA',
    officialSite: meta.officialSite,
    architecture: meta.architecture || 'x86/x64',
    extension: ext,
    systemReq: meta.systemReq || 'Windows',
    sizeBytes: file.size,
    oid: file.oid,
    xetHash: file.xetHash,
  };
}
